#!/usr/bin/env python3
"""Measure how much the picture moves through each scroll-world clip.

Writes assets/vid/motion-profile.js, which the scrub engine uses to pace the
film: it hands out scroll distance in proportion to on-screen motion, so the
camera keeps an even speed through dives and connectors instead of crawling
through one clip and whipping through the next.

Usage (from the repo root, needs ffmpeg + numpy):
    python3 tools/motion-profile.py
Re-run it whenever a clip in assets/vid/encoded changes.
"""
import json, pathlib, subprocess
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'assets/vid/encoded'
OUT = ROOT / 'assets/vid/motion-profile.js'
SAMPLES = 64      # points per clip curve
W, H = 96, 54     # analysis size: enough for camera motion, blind to grain


def gray_frames(path):
    raw = subprocess.run(
        ['ffmpeg', '-v', 'error', '-i', str(path), '-vf', f'scale={W}:{H}:flags=area,format=gray',
         '-f', 'rawvideo', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(-1, H, W).astype(np.float32)


profiles = {}
for clip in sorted(SRC.glob('*.mp4')):
    f = gray_frames(clip)
    step = np.abs(np.diff(f, axis=0)).mean(axis=(1, 2))   # motion between frames
    cum = np.concatenate([[0.0], np.cumsum(step)])
    total = float(cum[-1])
    t = np.linspace(0, 1, len(cum))                      # time fraction of each frame
    ts = np.linspace(0, 1, SAMPLES + 1)
    curve = np.interp(ts, t, cum / max(total, 1e-6))
    profiles[clip.name] = {'total': round(total, 1), 'curve': [round(float(x), 4) for x in curve]}
    print(f'{clip.name}: total motion {total:.0f}')

OUT.write_text(
    '// Generated by tools/motion-profile.py. Do not edit by hand.\n'
    '// Per clip: total on-screen motion, and the share of it reached at each of\n'
    f'// {SAMPLES + 1} evenly spaced moments of the clip.\n'
    'window.SW_MOTION_PROFILE = ' + json.dumps(profiles, separators=(',', ':')) + ';\n')
print('wrote', OUT.relative_to(ROOT))
